def set_cjk(doc, font=FONT):
    normal = doc.styles["Normal"]
    normal.font.name = font
    normal.font.size = Pt(10.5)
    _set_eastasia(normal.element, font)
    for i in range(1, 4):
        try:
            st = doc.styles[f"Heading {i}"]
            st.font.name = font
            _set_eastasia(st.element, font)
        except Exception:
            pass
    try:
        st = doc.styles["Title"]
        st.font.name = font
        _set_eastasia(st.element, font)
    except Exception:
        pass

def _set_eastasia(el, font):
    rpr = el.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:eastAsia"), font)

def set_cell_bg(cell, color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tcPr.append(shd)

def shade_header_row(row):
    for c in row.cells:
        set_cell_bg(c, "2F5496")
        for p in c.paragraphs:
            for r in p.runs:
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
                r.font.bold = True

def add_para(doc, text="", size=10.5, bold=False, italic=False, color=None, align=None, space_after=4):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if text:
        run = p.add_run(text)
        run.bold = bold
        run.italic = italic
        run.font.size = Pt(size)
        if color is not None:
            run.font.color.rgb = color
    return p

def add_steps(doc, steps):
    for i, s in enumerate(steps, 1):
        p = doc.add_paragraph(style="List Number")
        p.paragraph_format.space_after = Pt(3)
        r = p.add_run(s)
        r.font.size = Pt(10.5)

def add_bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(2)
        p.add_run(it).font.size = Pt(10.5)

def add_field_table(doc, headers, rows, widths=None):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        run = hdr[i].paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(10)
    shade_header_row(table.rows[0])
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            r.font.size = Pt(9.5)
    if widths:
        for i, w in enumerate(widths):
            for row in table.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return table

def add_note(doc, text, kind="注意"):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(f"【{kind}】")
    r.bold = True
    r.font.color.rgb = RGBColor(0xC0, 0x00, 0x00) if kind in ("注意", "警告") else RGBColor(0x1F, 0x49, 0x7D)
    r.font.size = Pt(10)
    r2 = p.add_run(text)
    r2.font.size = Pt(10)

def add_screenshot(doc, label):
    """在文档中插入一个灰底「截图位置」占位框，并附图注，留空供粘贴截图。"""
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    set_cell_bg(cell, "EDEDED")
    cell.width = Cm(15.5)
    # 固定行高
    tr = cell._tc.getparent()
    trPr = tr.get_or_add_trPr()
    trHeight = OxmlElement("w:trHeight")
    trHeight.set(qn("w:val"), str(int(5.0 * 567)))
    trHeight.set(qn("w:hRule"), "exact")
    trPr.append(trHeight)
    # 内容
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(40)
    r = p.add_run("[ 截图位置 ]")
    r.bold = True
    r.font.size = Pt(12)
    r.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
    p2 = cell.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run("（请在此处粘贴对应界面截图）")
    r2.font.size = Pt(10)
    r2.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    p3 = cell.add_paragraph()
    p3.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p3.paragraph_format.space_after = Pt(40)
    r3 = p3.add_run(label)
    r3.font.size = Pt(9.5)
    r3.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    # 图注
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(8)
    rc = cap.add_run(f"图：{label}")
    rc.italic = True
    rc.font.size = Pt(9)
    rc.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
    return table

def add_toc(doc):
    add_para(doc, "目录", size=14, bold=True)
    p = doc.add_paragraph()
    run = p.add_run()
    fld1 = OxmlElement("w:fldChar"); fld1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText"); instr.set(qn("xml:space"), "preserve")
    instr.text = 'TOC \\o "1-3" \\h \\z \\u'
    fld2 = OxmlElement("w:fldChar"); fld2.set(qn("w:fldCharType"), "separate")
    t = OxmlElement("w:t"); t.text = "（打开本文档后，在目录区域点击右键选择「更新域」→「更新整个目录」即可生成目录）"
    fld3 = OxmlElement("w:fldChar"); fld3.set(qn("w:fldCharType"), "end")
    run._r.append(fld1); run._r.append(instr); run._r.append(fld2); run._r.append(t); run._r.append(fld3)
    add_para(doc, "")

# ----------------------------------------------------------------------------
# 章节渲染
# ----------------------------------------------------------------------------
def render_chapter(doc, chapter):
    doc.add_heading(chapter["title"], level=1)
    if chapter.get("intro"):
        add_para(doc, chapter["intro"], size=10.5)
    for sub in chapter["subs"]:
        doc.add_heading(sub["title"], level=2)
        if sub.get("nav"):
            add_para(doc, f"菜单路径：{sub['nav']}", size=9.5, italic=True, color=RGBColor(0x60, 0x60, 0x60))
        if sub.get("desc"):
            add_para(doc, sub["desc"], size=10.5)
        if sub.get("shot"):
            add_screenshot(doc, sub["shot"])
        if sub.get("steps"):
            add_para(doc, "操作步骤：", bold=True, size=10.5)
            add_steps(doc, sub["steps"])
        if sub.get("fields"):
            add_para(doc, "关键字段说明：", bold=True, size=10.5)
            headers = sub.get("field_headers", ["字段", "必填", "说明"])
            add_field_table(doc, headers, sub["fields"])
        if sub.get("note"):
            add_note(doc, sub["note"], kind=sub.get("note_kind", "注意"))
        if sub.get("extra"):
            for blk in sub["extra"]:
                if blk[0] == "bullets":
                    add_bullets(doc, blk[1])
                elif blk[0] == "note":
                    add_note(doc, blk[1], kind=blk[2] if len(blk) > 2 else "注意")

